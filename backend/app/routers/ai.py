import json
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field
from app.ai.openai_service import openai_service
from app.routers.auth import get_current_user
from app.models.user import User

router = APIRouter(prefix="/ai", tags=["AI & LLM Services"])


class AIChatMessage(BaseModel):
    message: str = Field(..., min_length=1, description="The user query or prompt")
    history: Optional[list[dict]] = Field(default_factory=list, description="Recent conversation turns")
    system_prompt: Optional[str] = Field(None, description="Optional custom system prompt")
    api_key: Optional[str] = Field(None, description="Optional custom API key for this request")
    base_url: Optional[str] = Field(None, description="Optional custom base URL endpoint (e.g. https://your-custom-endpoint.com)")
    model_id: Optional[str] = Field(None, description="Optional custom model name")


class AIChatResponse(BaseModel):
    reply: str
    model: str
    provider: str
    suggestions: list[str]
    warning: Optional[str] = None


class AIStatusResponse(BaseModel):
    configured: bool
    base_url: str
    model_id: str
    masked_api_key: str


class AITestRequest(BaseModel):
    api_key: Optional[str] = None
    base_url: Optional[str] = None
    model_id: Optional[str] = None


@router.post("/chat", response_model=AIChatResponse)
def chat_with_ai(
    request: AIChatMessage,
    current_user: User = Depends(get_current_user),
):
    """Chat endpoint for Samarthya AI Assistant.

    Connects to the configured or custom OpenAI endpoint/model.
    Gracefully falls back to local domain heuristics if no key is provided.
    """
    try:
        res = openai_service.chat(
            user_message=request.message,
            conversation_history=request.history,
            system_prompt=request.system_prompt,
            custom_api_key=request.api_key,
            custom_base_url=request.base_url,
            custom_model=request.model_id,
        )
        return AIChatResponse(
            reply=res.get("reply", ""),
            model=res.get("model", openai_service.model_id),
            provider=res.get("provider", "openai"),
            suggestions=res.get("suggestions", []),
            warning=res.get("warning"),
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"AI chat error: {str(e)}")


@router.post("/chat/stream")
def stream_chat_with_ai(
    request: AIChatMessage,
    current_user: User = Depends(get_current_user),
):
    """Realtime streaming chat endpoint for Samarthya AI Assistant.

    Yields token chunks as they are generated by the custom OpenAI endpoint.
    Format: Server-Sent Events (SSE).
    """
    def event_generator():
        try:
            for chunk in openai_service.stream_chat(
                user_message=request.message,
                conversation_history=request.history,
                system_prompt=request.system_prompt,
                custom_api_key=request.api_key,
                custom_base_url=request.base_url,
                custom_model=request.model_id,
            ):
                payload = json.dumps({"content": chunk})
                yield f"data: {payload}\n\n"
            yield "data: [DONE]\n\n"
        except Exception as e:
            err_payload = json.dumps({"error": str(e)})
            yield f"data: {err_payload}\n\n"
            yield "data: [DONE]\n\n"

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )


@router.get("/status", response_model=AIStatusResponse)
def get_ai_status(
    current_user: User = Depends(get_current_user),
):
    """Returns status of OpenAI integration, configured base_url, model_id, and masked key."""
    status = openai_service.get_status()
    return AIStatusResponse(
        configured=status["configured"],
        base_url=status["base_url"],
        model_id=status["model_id"],
        masked_api_key=status["masked_api_key"],
    )


@router.post("/test")
def test_ai_connection(
    request: Optional[AITestRequest] = None,
    current_user: User = Depends(get_current_user),
):
    """Tests the OpenAI connection with a minimal prompt using default or custom credentials."""
    req = request or AITestRequest()
    target_key = (req.api_key or openai_service.api_key).strip()
    target_base = (req.base_url or openai_service.base_url).strip() or "https://api.openai.com/v1"
    target_model = (req.model_id or openai_service.model_id).strip() or "gpt-4o-mini"

    if not openai_service.is_key_valid(target_key):
        return {
            "success": False,
            "configured": False,
            "message": "OpenAI API key is empty or not configured. Running in local fallback mode.",
            "base_url": target_base,
            "model_id": target_model,
        }

    try:
        from openai import OpenAI
        client = OpenAI(
            api_key=target_key,
            base_url=target_base,
            timeout=15.0,
        )

        res = client.chat.completions.create(
            model=target_model,
            messages=[{"role": "user", "content": "Hello! Reply with 'OK' only."}],
            max_tokens=10,
        )
        text = res.choices[0].message.content or ""
        return {
            "success": True,
            "configured": True,
            "base_url": target_base,
            "model_id": target_model,
            "response": text.strip(),
        }
    except Exception as e:
        return {
            "success": False,
            "configured": True,
            "base_url": target_base,
            "model_id": target_model,
            "error": str(e),
        }
